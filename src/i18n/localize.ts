export function localizeGenre(genreName: string, lang: Language): string {
  if (lang === 'en' || !genreName) return genreName;
  const match = GENRE_TRANSLATIONS[genreName];
  if (match && match[lang]) return match[lang]!;
  return genreName;
}

export function getTranslation(lang: Language): TranslationDict {
  return TRANSLATIONS[lang] || TRANSLATIONS.en;
}

