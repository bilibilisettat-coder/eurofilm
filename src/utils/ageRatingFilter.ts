/**
 * Guesses and verifies whether a movie or anime is targeted for under-18 (-18)
 */
export function isTargetedForUnder18(item: MediaCheckItem): boolean {
  if (item.adult) return false;

  const titleLower = (item.title || '').toLowerCase();
  const origLower = (item.original_title || '').toLowerCase();
  const overviewLower = (item.overview || '').toLowerCase();
  const fullContent = `${titleLower} ${origLower} ${overviewLower}`;

  // 1. Strict Exclusion check
  for (const block of MATURE_BLOCKLIST) {
    if (titleLower.includes(block) || origLower.includes(block)) {
      return false;
    }
  }

  // Horror TMDB genre ID (27) is never -18
  if (item.genre_ids?.includes(27)) {
    return false;
  }
  if (item.genres?.some((g) => g.toLowerCase().includes('horror') || g.toLowerCase().includes('ecchi'))) {
    return false;
  }

  // 2. High confidence match by title keyword / franchise pattern
  for (const pat of UNDER_18_TITLE_PATTERNS) {
    if (titleLower.includes(pat) || origLower.includes(pat)) {
      return true;
    }
  }

  // 3. Animation (TMDB 16) or Family (TMDB 10751) genres
  if (item.genre_ids?.includes(16) || item.genre_ids?.includes(10751)) {
    return true;
  }
  if (item.genres?.some((g) => {
    const gl = g.toLowerCase();
    return gl.includes('animation') || gl.includes('family') || gl.includes('kids');
  })) {
    return true;
  }

  // 4. Adventure (12) + Comedy (35) or Fantasy (14) without crime/thriller
  if (
    item.genre_ids?.some((g) => [12, 14, 35].includes(g)) &&
    !item.genre_ids?.some((g) => [80, 53, 9648].includes(g))
  ) {
    return true;
  }

  return false;
}

/**
 * Determines whether media is targeted for +18 (mature, adult, psychological thriller, R-rated)
 */
export function isTargetedForOver18(item: MediaCheckItem): boolean {
  if (item.adult) return true;

  const titleLower = (item.title || '').toLowerCase();
  const origLower = (item.original_title || '').toLowerCase();
  const fullContent = `${titleLower} ${origLower} ${(item.overview || '').toLowerCase()}`;

  for (const block of MATURE_BLOCKLIST) {
    if (fullContent.includes(block)) {
      return true;
    }
  }

  // TMDB Genres: 27 (Horror), 80 (Crime), 53 (Thriller)
  if (item.genre_ids?.some((g) => [27, 80, 53].includes(g))) {
    return true;
  }

  if (item.genres?.some((g) => {
    const gl = g.toLowerCase();
    return gl.includes('horror') || gl.includes('crime') || gl.includes('thriller') || gl.includes('ecchi') || gl.includes('erotic');
  })) {
    return true;
  }

  return false;
}
